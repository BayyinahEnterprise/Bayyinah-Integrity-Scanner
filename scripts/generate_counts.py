"""Keep the README's counts equal to the code's.

The block between the two markers in README.md is generated from the
mechanism registry. ``--write`` regenerates it; with no argument the
script exits 1 if the README is out of date. A test runs the check, so
a count in the README cannot drift from the registry it describes.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
BEGIN, END = "<!-- BAYYINAH_COUNTS_AUTO_BEGIN -->", "<!-- BAYYINAH_COUNTS_AUTO_END -->"


def block() -> str:
    from domain.config import (
        BATIN_MECHANISMS, MECHANISM_REGISTRY, ROUTING_MECHANISMS, TIER,
        ZAHIR_MECHANISMS,
    )
    tiers = {t: sum(1 for m in MECHANISM_REGISTRY if TIER[m] == t) for t in (0, 1, 2, 3)}
    return "\n".join([
        BEGIN,
        "<!-- Generated by scripts/generate_counts.py. Do not edit by hand. -->",
        f"The scanner registers **{len(MECHANISM_REGISTRY)} mechanisms**: "
        f"{len(ZAHIR_MECHANISMS)} in what is rendered or extracted as text, "
        f"{len(BATIN_MECHANISMS)} in a file's inner structure, and "
        f"{len(ROUTING_MECHANISMS)} about the scanner's own routing. "
        f"By tier: {tiers[1]} verified, {tiers[2]} structural, "
        f"{tiers[3]} interpretive, {tiers[0]} routing.",
        END,
    ])


def main() -> int:
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    new = block()
    if BEGIN in text and END in text:
        current = text[text.index(BEGIN): text.index(END) + len(END)]
        updated = text.replace(current, new)
    else:
        current, updated = "", text
    if "--write" in sys.argv:
        if not current:
            anchor = "## What Bayyinah detects\n"
            updated = text.replace(anchor, anchor + "\n" + new + "\n", 1)
        readme.write_text(updated, encoding="utf-8")
        return 0
    if current != new:
        print("README counts are out of date; run: python scripts/generate_counts.py --write")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
